-- Skema sistem internal Tenda Indonesia x HKA Management untuk PostgreSQL. Terjemahan db/skema.sql: tabel,
-- CHECK, foreign key, dan indeksnya sama. Kalau salah satu berkas diubah, ubah juga yang lain dan naikkan
-- VERSI_SKEMA di src/lib/db.ts, karena berkas ini hanya dijalankan kalau versi yang tersimpan tertinggal.
-- Semua perintah harus aman diulang. Kolom baru untuk tabel yang sudah ada ditambahkan dengan
-- ALTER TABLE ... ADD COLUMN IF NOT EXISTS di akhir berkas.
--
-- Perbedaan dengan versi SQLite:
--  - Uang dan waktu epoch memakai BIGINT. INTEGER PostgreSQL hanya sampai sekitar 2,1 miliar, sedangkan batas
--    uang di aplikasi Rp 100 miliar dan pembatas.mulai berisi milidetik.
--  - Teks memakai COLLATE "C" supaya urutan dan perbandingan sama dengan SQLite (urutan byte), tidak
--    bergantung pada locale basis data di server.
--  - Pemicu jejak audit ditulis sebagai fungsi plpgsql.

CREATE TABLE IF NOT EXISTS pengguna (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT COLLATE "C" NOT NULL,
  username TEXT COLLATE "C" NOT NULL UNIQUE,
  sandi TEXT COLLATE "C" NOT NULL,
  peran TEXT COLLATE "C" NOT NULL CHECK (peran IN ('admin', 'sales', 'gudang', 'kru', 'partner')),
  aktif INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS sesi (
  token TEXT COLLATE "C" PRIMARY KEY,
  pengguna_id INTEGER NOT NULL REFERENCES pengguna (id) ON DELETE CASCADE,
  kedaluwarsa TEXT COLLATE "C" NOT NULL,
  batas TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS pembatas (
  kunci TEXT COLLATE "C" PRIMARY KEY,
  mulai BIGINT NOT NULL,
  jumlah INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS perangkat (
  token TEXT COLLATE "C" NOT NULL,
  pengguna_id INTEGER NOT NULL REFERENCES pengguna (id) ON DELETE CASCADE,
  kedaluwarsa TEXT COLLATE "C" NOT NULL,
  PRIMARY KEY (token, pengguna_id)
);

CREATE TABLE IF NOT EXISTS pengaturan (
  kunci TEXT COLLATE "C" PRIMARY KEY,
  nilai TEXT COLLATE "C" NOT NULL
);

CREATE TABLE IF NOT EXISTS aset (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode TEXT COLLATE "C" NOT NULL UNIQUE,
  nama TEXT COLLATE "C" NOT NULL,
  kategori TEXT COLLATE "C" NOT NULL,
  ukuran TEXT COLLATE "C" NOT NULL DEFAULT '',
  satuan TEXT COLLATE "C" NOT NULL DEFAULT 'unit',
  jumlah INTEGER NOT NULL CHECK (jumlah >= 0),
  harga BIGINT NOT NULL DEFAULT 0 CHECK (harga >= 0),
  deskripsi TEXT COLLATE "C" NOT NULL DEFAULT '',
  tampil_web INTEGER NOT NULL DEFAULT 1,
  aktif INTEGER NOT NULL DEFAULT 1,
  kapasitas TEXT COLLATE "C" NOT NULL DEFAULT '',
  cocok TEXT COLLATE "C" NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS aset_foto (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aset_id INTEGER NOT NULL REFERENCES aset (id) ON DELETE CASCADE,
  berkas TEXT COLLATE "C" NOT NULL UNIQUE,
  urutan INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_foto_aset ON aset_foto (aset_id, urutan);

CREATE TABLE IF NOT EXISTS perawatan (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aset_id INTEGER NOT NULL REFERENCES aset (id) ON DELETE CASCADE,
  jumlah INTEGER NOT NULL CHECK (jumlah > 0),
  mulai TEXT COLLATE "C" NOT NULL,
  selesai TEXT COLLATE "C",
  catatan TEXT COLLATE "C" NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS kontak (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT COLLATE "C" NOT NULL,
  perusahaan TEXT COLLATE "C" NOT NULL DEFAULT '',
  telepon TEXT COLLATE "C" NOT NULL DEFAULT '',
  email TEXT COLLATE "C" NOT NULL DEFAULT '',
  jenis TEXT COLLATE "C" NOT NULL DEFAULT 'perorangan' CHECK (jenis IN ('perorangan', 'korporat')),
  sumber TEXT COLLATE "C" NOT NULL DEFAULT '',
  tahap TEXT COLLATE "C" NOT NULL DEFAULT 'baru' CHECK (tahap IN ('baru', 'dihubungi', 'penawaran', 'menang', 'kalah')),
  kebutuhan TEXT COLLATE "C" NOT NULL DEFAULT '',
  tindak_lanjut TEXT COLLATE "C",
  dibuat TEXT COLLATE "C" NOT NULL
);

CREATE TABLE IF NOT EXISTS pesanan (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nomor TEXT COLLATE "C" NOT NULL UNIQUE,
  kontak_id INTEGER NOT NULL REFERENCES kontak (id),
  acara TEXT COLLATE "C" NOT NULL,
  lokasi TEXT COLLATE "C" NOT NULL DEFAULT '',
  mulai TEXT COLLATE "C" NOT NULL,
  selesai TEXT COLLATE "C" NOT NULL,
  status TEXT COLLATE "C" NOT NULL DEFAULT 'penawaran' CHECK (status IN ('penawaran', 'booking', 'berjalan', 'selesai', 'batal')),
  diskon BIGINT NOT NULL DEFAULT 0 CHECK (diskon >= 0),
  catatan TEXT COLLATE "C" NOT NULL DEFAULT '',
  tgl_faktur TEXT COLLATE "C",
  dibuat TEXT COLLATE "C" NOT NULL,
  CHECK (selesai >= mulai)
);

-- jumlah dan hari tetap INTEGER (batasnya 100.000). Kueri yang mengalikannya menaruh harga (BIGINT) di
-- depan, supaya perkaliannya dihitung sebagai BIGINT dan tidak meluap.
CREATE TABLE IF NOT EXISTS pesanan_baris (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pesanan_id INTEGER NOT NULL REFERENCES pesanan (id) ON DELETE CASCADE,
  aset_id INTEGER REFERENCES aset (id),
  deskripsi TEXT COLLATE "C" NOT NULL,
  jumlah INTEGER NOT NULL CHECK (jumlah > 0),
  hari INTEGER NOT NULL DEFAULT 1 CHECK (hari > 0),
  harga BIGINT NOT NULL CHECK (harga >= 0)
);

CREATE TABLE IF NOT EXISTS pembayaran (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pesanan_id INTEGER NOT NULL REFERENCES pesanan (id) ON DELETE CASCADE,
  tanggal TEXT COLLATE "C" NOT NULL,
  jumlah BIGINT NOT NULL CHECK (jumlah > 0),
  metode TEXT COLLATE "C" NOT NULL DEFAULT 'transfer',
  catatan TEXT COLLATE "C" NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS biaya (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal TEXT COLLATE "C" NOT NULL,
  jenis TEXT COLLATE "C" NOT NULL CHECK (jenis IN ('langsung', 'operasional')),
  kategori TEXT COLLATE "C" NOT NULL,
  pesanan_id INTEGER REFERENCES pesanan (id) ON DELETE SET NULL,
  jumlah BIGINT NOT NULL CHECK (jumlah > 0),
  keterangan TEXT COLLATE "C" NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS tugas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pesanan_id INTEGER NOT NULL REFERENCES pesanan (id) ON DELETE CASCADE,
  jenis TEXT COLLATE "C" NOT NULL CHECK (jenis IN ('survei', 'pasang', 'bongkar', 'lainnya')),
  tanggal TEXT COLLATE "C" NOT NULL,
  kru TEXT COLLATE "C" NOT NULL DEFAULT '',
  checklist TEXT COLLATE "C" NOT NULL DEFAULT '[]',
  selesai INTEGER NOT NULL DEFAULT 0,
  catatan TEXT COLLATE "C" NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS periode (
  bulan TEXT COLLATE "C" PRIMARY KEY,
  pendapatan BIGINT NOT NULL,
  biaya_langsung BIGINT NOT NULL,
  biaya_operasional BIGINT NOT NULL,
  cadangan BIGINT NOT NULL,
  pajak BIGINT NOT NULL,
  laba_bersih BIGINT NOT NULL,
  bagian_tenda BIGINT NOT NULL,
  bagian_hka BIGINT NOT NULL,
  dibayar_tenda BIGINT NOT NULL DEFAULT 0,
  dibayar_hka BIGINT NOT NULL DEFAULT 0,
  dikunci TEXT COLLATE "C" NOT NULL,
  catatan TEXT COLLATE "C" NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_pesanan_rentang ON pesanan (mulai, selesai);
CREATE INDEX IF NOT EXISTS idx_pesanan_kontak ON pesanan (kontak_id);
CREATE INDEX IF NOT EXISTS idx_baris_pesanan ON pesanan_baris (pesanan_id);
CREATE INDEX IF NOT EXISTS idx_pembayaran_tanggal ON pembayaran (tanggal);
CREATE INDEX IF NOT EXISTS idx_biaya_tanggal ON biaya (tanggal);
CREATE INDEX IF NOT EXISTS idx_tugas_tanggal ON tugas (tanggal);

CREATE TABLE IF NOT EXISTS log_aktivitas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  waktu TEXT COLLATE "C" NOT NULL,
  pengguna_id INTEGER,
  pengguna TEXT COLLATE "C" NOT NULL,
  aksi TEXT COLLATE "C" NOT NULL,
  rincian TEXT COLLATE "C" NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_log_waktu ON log_aktivitas (waktu);

-- Jejak audit hanya bisa bertambah. Pesannya sama dengan pemicu di skema SQLite. TRUNCATE juga ditolak,
-- karena di PostgreSQL perintah itu tidak melewati pemicu DELETE.
CREATE OR REPLACE FUNCTION log_aktivitas_tolak_ubah() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Jejak audit tidak bisa diubah.';
END
$$;

CREATE OR REPLACE FUNCTION log_aktivitas_tolak_hapus() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Jejak audit tidak bisa dihapus.';
END
$$;

-- CREATE OR REPLACE TRIGGER butuh PostgreSQL 14 atau lebih baru.
CREATE OR REPLACE TRIGGER log_aktivitas_tanpa_ubah BEFORE UPDATE ON log_aktivitas
  FOR EACH ROW EXECUTE FUNCTION log_aktivitas_tolak_ubah();

CREATE OR REPLACE TRIGGER log_aktivitas_tanpa_hapus BEFORE DELETE ON log_aktivitas
  FOR EACH ROW EXECUTE FUNCTION log_aktivitas_tolak_hapus();

CREATE OR REPLACE TRIGGER log_aktivitas_tanpa_kosongkan BEFORE TRUNCATE ON log_aktivitas
  FOR EACH STATEMENT EXECUTE FUNCTION log_aktivitas_tolak_hapus();
